// Shared contracts for the demo care scenario (DEMO_IMPLEMENTATION_PLAN.md §4, NEXT_ACTIONS.md).
// Owner: integrator (A0). Feature modules import types only from here; they never
// import each other. Every adapter declares where its data comes from, so the UI can
// show "Live" or "Demo data" and a live error never silently switches to fixtures.
// Pure types: no React, DOM or API imports.

/** Where a domain's data comes from. Chosen by configuration, never by an error. */
export type DataSourceKind = 'live' | 'fixture';

// ---------- Provenance ----------

export type Source =
  | { kind: 'patient-input'; at: string }
  | { kind: 'message'; messageId: string; quote: string }
  | { kind: 'document'; documentId: string; page?: number; quote?: string }
  | { kind: 'doctor'; doctorId: string; at: string };

export type ConfirmationStatus = 'confirmed' | 'unconfirmed' | 'unknown' | 'conflict';

export interface Confirmation {
  status: ConfirmationStatus;
  by?: 'patient' | 'doctor';
  /** ISO 8601. */
  at?: string;
}

// ---------- Patient context (allergies, conditions, current medication) ----------

export type ContextKind = 'allergy' | 'condition' | 'medication';

export interface ContextItem {
  id: string;
  kind: ContextKind;
  /** Exactly what the patient or the source said. "Unknown" is a status, never an empty text. */
  text: string;
  source: Source;
  confirmation: Confirmation;
  /** Visible label, e.g. for an explicitly synthetic conflict in the demo seed. Never generated by inference. */
  note?: string;
}

export interface PatientContextAdapter {
  readonly source: DataSourceKind;
  load(signal?: AbortSignal): Promise<ContextItem[]>;
  add(kind: ContextKind, text: string): Promise<ContextItem>;
  confirm(id: string): Promise<ContextItem>;
  /** Patient states they do not know (kept as 'unknown', not deleted). */
  markUnknown(id: string): Promise<ContextItem>;
}

// ---------- Intake chat (collection only, no diagnosis) ----------

export interface IntakeMessage {
  id: string;
  role: 'patient' | 'assistant' | 'system';
  text: string;
  /** ISO 8601. */
  createdAt: string;
  /** Client id used for idempotent retries of patient messages. */
  clientMessageId?: string;
}

export interface IntakeResult {
  /** Always persisted first, even when the assistant fails or a safety rule stops it. */
  patientMessage: IntakeMessage;
  assistantMessage: IntakeMessage | null;
  /** Deterministic safety rule (not LLM text). When set, no assistant reply is produced. */
  redFlag: { message: string } | null;
  /** Explicit partial failure: the patient message is saved, the reply is not. */
  partialError: string | null;
}

export interface IntakeAdapter {
  readonly source: DataSourceKind;
  /** Name shown for assistant messages (from brand config). */
  readonly assistantName: string;
  load(signal?: AbortSignal): Promise<IntakeMessage[]>;
  /** Idempotent on clientMessageId: retrying never duplicates the patient message. */
  send(text: string, clientMessageId: string): Promise<IntakeResult>;
}

// ---------- Prescription scan, extraction and review ----------

export interface LocalDocument {
  uri: string;
  mimeType: string;
  fileName: string;
  sizeBytes?: number;
}

export interface ExtractedMedication {
  name: string | null;
  dose: string | null;
  /** Copied text, e.g. "1 cp dimineata". Never converted to hours. */
  frequency: string | null;
  duration: string | null;
}

export interface ExtractedDocument {
  id: string;
  documentType: 'prescription' | 'lab_result' | 'medical_letter' | 'other';
  fileName: string;
  medications: ExtractedMedication[];
  dates: { label: string | null; value: string | null }[];
  /** Extraction warnings, shown as-is. */
  warnings: string[];
  /** Source quote per field path (e.g. "medications.0.dose") when the extractor provides it. */
  sourceQuotes: Record<string, string>;
  /** ISO 8601. */
  extractedAt: string;
}

export interface ReviewedField {
  /** e.g. "medications.0.dose" */
  path: string;
  label: string;
  extracted: string | null;
  /** Value after the patient's review; null only if confirmed as not present. */
  value: string | null;
  confirmation: Confirmation;
  sourceQuote?: string;
}

/** A medication the patient confirmed from a reviewed document (transcription, not a new prescription). */
export interface ConfirmedMedication {
  id: string;
  documentId: string;
  name: string;
  /** Prescribed dose text, unchanged. */
  doseText: string;
  /** Prescribed instruction, verbatim (frequency text). */
  instructionOriginal: string;
  /** Prescribed duration text, verbatim; null when the prescription has none. */
  durationText: string | null;
  fields: ReviewedField[];
  confirmedAt: string;
}

export interface PrescriptionAdapter {
  readonly source: DataSourceKind;
  extract(document: LocalDocument, signal?: AbortSignal): Promise<ExtractedDocument>;
  /** Saves the reviewed fields; returns the medications that became confirmed context. */
  saveReview(documentId: string, fields: ReviewedField[]): Promise<ConfirmedMedication[]>;
  listConfirmed(signal?: AbortSignal): Promise<ConfirmedMedication[]>;
}

// ---------- Medication schedule and reminders ----------

export interface MedicationSchedule {
  id: string;
  medicationId: string;
  medication: string;
  doseText: string;
  /** Verbatim prescribed instruction. Choosing times never changes it. */
  instructionOriginal: string;
  /** "HH:MM" local times chosen explicitly by the patient. */
  times: string[];
  /** "YYYY-MM-DD", chosen explicitly. */
  startDate: string;
  /** "YYYY-MM-DD" inclusive, or null only when the patient confirmed "no end date given". */
  endDate: string | null;
  /** IANA time zone, e.g. "Europe/Bucharest". */
  timezone: string;
  status: 'active' | 'ended' | 'cancelled';
  confirmedAt: string;
}

export interface ScheduleAdapter {
  readonly source: DataSourceKind;
  list(signal?: AbortSignal): Promise<MedicationSchedule[]>;
  save(schedule: Omit<MedicationSchedule, 'id' | 'status' | 'confirmedAt'>): Promise<MedicationSchedule>;
  cancel(id: string): Promise<MedicationSchedule>;
}

// ---------- Case for the doctor: summary with sources, feedback, optional variants ----------

export interface PersonRef {
  id: string;
  fullName: string;
}

export interface SummaryItem {
  id: string;
  text: string;
  /** At least one source; a statement without a source is shown as unsourced. */
  sources: Source[];
  negated?: boolean;
  uncertain?: boolean;
}

/**
 * Derived, versioned representation. It never replaces the originals. Completeness is
 * NOT a property claimed here: the UI computes which patient messages no item cites.
 */
export interface CaseSummary {
  version: number;
  createdAt: string;
  generatedBy: 'fixture' | 'ai';
  items: SummaryItem[];
}

export interface DoctorFeedback {
  id: string;
  caseId: string;
  doctor: PersonRef;
  /** The doctor's own words, exactly as sent. */
  text: string;
  createdAt: string;
  /** Set when the doctor started from an optional AI variant (always edited and signed by the doctor). */
  basedOnVariant: number | null;
}

/** Optional decision-support variants. Doctor-only; never reachable from patient views. */
export interface DecisionVariants {
  generatedBy: 'fixture' | 'ai';
  createdAt: string;
  options: { option: string; reasoning: string; confidence: string; confirmationPath: string }[];
  missingInformation: string[];
  contradictions: string[];
}

export type CaseStatus = 'draft' | 'pending_doctor' | 'answered';

export interface CareCase {
  id: string;
  status: CaseStatus;
  patient: PersonRef;
  doctor: PersonRef;
  submittedAt: string | null;
  messages: IntakeMessage[];
  documents: ExtractedDocument[];
  context: ContextItem[];
  medications: ConfirmedMedication[];
}

export interface CareCaseAdapter {
  readonly source: DataSourceKind;
  getCase(signal?: AbortSignal): Promise<CareCase>;
  /** Patient action: sends the collected case to the doctor. */
  submit(): Promise<CareCase>;
  getSummary(signal?: AbortSignal): Promise<CaseSummary | null>;
  getFeedback(signal?: AbortSignal): Promise<DoctorFeedback | null>;
  /** Doctor action. */
  sendFeedback(text: string, basedOnVariant: number | null): Promise<DoctorFeedback>;
  /** Optional; absent when variants are disabled. Doctor-only. */
  requestVariants?: () => Promise<DecisionVariants>;
}
