export type UserRole = 'patient' | 'doctor';

export interface PublicDoctor {
  id: string;
  fullName: string;
  specialty: string;
  clinic: string;
}

/** Returned by the backend, never inferred from Google metadata or URL state. */
export interface AccountProfile {
  id: string;
  email: string;
  fullName: string;
  role: UserRole;
  activeDoctors: PublicDoctor[];
}

export type ConnectionStatus = 'pending' | 'accepted' | 'rejected' | 'cancelled';

export interface ConnectionRequest {
  id: string;
  status: ConnectionStatus;
  createdAt: string;
  doctor: PublicDoctor;
  patient: { id: string; fullName: string };
}

export interface ConnectionCode {
  code: string;
  /** Canonical HTTPS app URL generated by the backend. */
  url: string;
}
